#!/usr/bin/env node
/**
 * `npm run build:installer` → the two files the site serves for servers (commit
 * them; deploying the site is an rsync of site/):
 *
 *   site/server/bootstrap.mjs   src/server/bootstrap.ts bundled for plain Node 24
 *   site/install                scripts/server-install.sh with the Node version and
 *                               the bootstrap's sha256 stamped in
 *
 * The bootstrap may load neither electron nor node-pty. The output is
 * deterministic, so it changes only when its sources do.
 */
import { build } from 'esbuild'
import { createHash } from 'node:crypto'
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { SERVER_NODE_VERSION, electronGuardPlugin, noNativeGuardPlugin } from './server-bundle.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const siteDir = path.join(root, 'site')

/** The bootstrap's source, bundled (no file written). Exported for the test that checks the committed copy. */
export async function bundleBootstrap() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ['src/server/bootstrap.ts'],
    bundle: true,
    write: false,
    platform: 'node',
    target: 'node24',
    format: 'esm',
    banner: {
      js: "// DevTool server bootstrap. Generated by scripts/build-installer.mjs from src/server/bootstrap.ts; do not edit.\nimport { createRequire as __devtoolCreateRequire } from 'node:module'; const require = __devtoolCreateRequire(import.meta.url);"
    },
    plugins: [electronGuardPlugin(root), noNativeGuardPlugin(root)],
    legalComments: 'none',
    logLevel: 'warning'
  })
  return result.outputFiles[0].contents
}

export function renderInstaller(bootstrapSha256) {
  const template = fs.readFileSync(path.join(root, 'scripts/server-install.sh'), 'utf8')
  return template
    .replace('@@NODE_VERSION@@', SERVER_NODE_VERSION)
    .replace('@@BOOTSTRAP_SHA256@@', bootstrapSha256)
}

async function main() {
  const bootstrap = await bundleBootstrap()
  const sha = createHash('sha256').update(bootstrap).digest('hex')
  fs.mkdirSync(path.join(siteDir, 'server'), { recursive: true })
  fs.writeFileSync(path.join(siteDir, 'server/bootstrap.mjs'), bootstrap)
  fs.writeFileSync(path.join(siteDir, 'install'), renderInstaller(sha), { mode: 0o755 })
  fs.chmodSync(path.join(siteDir, 'install'), 0o755)
  console.log(`build:installer site/server/bootstrap.mjs ${(bootstrap.length / 1024).toFixed(0)} KiB sha256 ${sha}`)
  console.log(`build:installer site/install (Node ${SERVER_NODE_VERSION})`)
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((err) => {
    if (!err?.errors) console.error(err)
    console.error('build:installer failed')
    process.exit(1)
  })
}
